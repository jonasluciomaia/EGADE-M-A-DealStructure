'use strict';
(function(){
  const n=v=>Number.isFinite(Number(v))?Number(v):0;
  const pct=v=>n(v)/100;
  window.calculateDeal=function(input,override){
    const a=input.a,b=input.b,d=input.deal;
    const cashPct=override===undefined?pct(d.cashPct):override;
    const stockPct=1-cashPct,tax=pct(d.taxRate);
    const aEquity=n(a.ev)-n(a.netDebt),bEquity=n(b.ev)-n(b.netDebt);
    const aImpliedPrice=n(a.shares)>0?aEquity/n(a.shares):0;
    const bImpliedPrice=n(b.shares)>0?bEquity/n(b.shares):0;
    const offerPrice=n(b.marketPrice)*(1+pct(d.premium));
    const purchasePrice=offerPrice*n(b.shares);
    const transactionCosts=Math.max(0,n(d.transactionCosts));
    const totalUses=purchasePrice+transactionCosts;
    const cashConsideration=purchasePrice*cashPct;
    const stockConsideration=purchasePrice*stockPct;
    const cashFundingRequirement=cashConsideration+transactionCosts;
    const cashUsed=Math.min(Math.max(0,n(a.cashAvailable)),Math.max(0,cashFundingRequirement));
    const newDebt=Math.max(0,cashFundingRequirement-cashUsed);
    const preTaxInterest=newDebt*pct(a.costDebt);
    const taxShield=preTaxInterest*tax;
    const afterTaxInterest=preTaxInterest-taxShield;
    const lostPreTaxCashIncome=cashUsed*pct(a.cashReturn);
    const lostAfterTaxCashIncome=lostPreTaxCashIncome*(1-tax);
    const newShares=n(a.marketPrice)>0?stockConsideration/n(a.marketPrice):0;
    const maxNewShares=n(a.shares)*pct(a.maxShareIssuancePct);
    const stockFirepower=maxNewShares*n(a.marketPrice);
    const totalFirepower=n(a.cashAvailable)+n(a.debtCapacity)+stockFirepower;
    const exchangeRatio=n(b.shares)>0?newShares/n(b.shares):0;
    const cashPerTargetShare=n(b.shares)>0?cashConsideration/n(b.shares):0;
    const pfShares=n(a.shares)+newShares;
    const aOwnership=pfShares>0?n(a.shares)/pfShares:0;
    const bOwnership=pfShares>0?newShares/pfShares:0;
    const aEPS=n(a.shares)>0?n(a.netIncome)/n(a.shares):0;
    const earningsYield=n(a.marketPrice)>0?aEPS/n(a.marketPrice):0;
    const afterTaxDebtCost=pct(a.costDebt)*(1-tax);
    const afterTaxCashReturn=pct(a.cashReturn)*(1-tax);
    const before=n(a.netIncome)+n(b.netIncome)-afterTaxInterest-lostAfterTaxCashIncome;
    const afterTaxSynergies=n(d.synergies)*(1-tax);
    const after=before+afterTaxSynergies;
    const pfEPSBefore=pfShares>0?before/pfShares:0;
    const pfEPSAfter=pfShares>0?after/pfShares:0;
    const accDilBefore=aEPS!==0?pfEPSBefore/aEPS-1:0;
    const accDilAfter=aEPS!==0?pfEPSAfter/aEPS-1:0;
    const cashWeight=totalUses>0?cashUsed/totalUses:0;
    const debtWeight=totalUses>0?newDebt/totalUses:0;
    const stockWeight=totalUses>0?stockConsideration/totalUses:0;
    const financingCost=cashWeight*afterTaxCashReturn+debtWeight*afterTaxDebtCost+stockWeight*pct(a.costEquity);
    const intrinsicPremium=bImpliedPrice!==0?offerPrice/bImpliedPrice-1:0;
    return {aEquity,bEquity,aImpliedPrice,bImpliedPrice,offerPrice,purchasePrice,transactionCosts,totalUses,cashPct,stockPct,cashConsideration,stockConsideration,cashFundingRequirement,cashUsed,newDebt,preTaxInterest,taxShield,afterTaxInterest,lostPreTaxCashIncome,lostAfterTaxCashIncome,cashWeight,debtWeight,stockWeight,newShares,maxNewShares,stockFirepower,totalFirepower,exchangeRatio,cashPerTargetShare,pfShares,aOwnership,bOwnership,aEPS,earningsYield,afterTaxDebtCost,afterTaxCashReturn,combinedBeforeSynergies:before,afterTaxSynergies,combinedAfterSynergies:after,pfEPSBefore,pfEPSAfter,accDilBefore,accDilAfter,financingCost,intrinsicPremium,debtCapacityExceeded:newDebt>n(a.debtCapacity),debtCapacityGap:Math.max(0,newDebt-n(a.debtCapacity)),shareCapacityExceeded:newShares>maxNewShares,shareCapacityGap:Math.max(0,newShares-maxNewShares),totalFirepowerExceeded:totalUses>totalFirepower,totalFirepowerGap:Math.max(0,totalUses-totalFirepower)};
  };
})();
